export function InkHeart({ className }: { className?: string }) {
  const ref = useRef<SVGSVGElement>(null);
  useEffect(() => {
    const el = ref.current;
    if (!el || typeof IntersectionObserver === "undefined") return;
    const io = new IntersectionObserver(
      ([e]) => { if (e.isIntersecting) el.setAttribute("data-on", ""); else el.removeAttribute("data-on"); },
      { threshold: 0.6 },
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);
  return (
    <svg ref={ref} className={"ink-heart" + (className ? " " + className : "")} viewBox="0 0 100 97" aria-hidden="true" focusable="false">
      {PIECES.map(([d, w, s, e], i) => (
        <path key={i} className="ink-seg" d={d} pathLength={1} fill="none" stroke="currentColor" strokeWidth={w} strokeLinecap="round"
          style={{ ["--s" as string]: s, ["--e" as string]: e }} />
      ))}
    </svg>
  );
}
